// 날짜마다 다른 6개 (같은 날엔 같은 팁, '새로 받기'를 누르면 다음 6개)
export function tipsFor(page = 0, count = 6) {
  const day = Math.floor((Date.now() + 9 * 3600 * 1000) / 86400000); // 한국 날짜 기준
  const start = ((day * 7 + page) * count) % TIPS.length;
  return Array.from({ length: count }, (_, i) => TIPS[(start + i) % TIPS.length]);
}
